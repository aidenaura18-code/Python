#for loop
#A for loop is used when we know how many times we want to repeat something.


for i in range (5):
    print("hello")

for i in range(2,5):
    print("hello")

for i in range(5):
    print(i)

n="hello"
for i in n:
    print(i)

for i in range(11):
    print(i)

mul=5
for i in range(1,11):
    print(mul,"*",i,"=",mul*i)

mul=2
for i in range(1,11):
    print(mul,"x",i,"=",mul*i)